from abc import ABC, abstractmethod
from app.schemas.vehicle_schema import VehicleCreate, VehicleUpdate

class VehicleService(ABC):
    @abstractmethod
    async def create(self, vehicle: VehicleCreate): ...
    @abstractmethod
    async def find_all(self): ...
    @abstractmethod
    async def find_by_user(self, user_id: str): ...
    @abstractmethod
    async def find_by_id(self, vehicle_id: str): ...
    @abstractmethod
    async def update(self, vehicle_id: str, data: VehicleUpdate): ...
    @abstractmethod
    async def delete(self, vehicle_id: str): ...
