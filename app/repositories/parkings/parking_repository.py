from abc import ABC, abstractmethod

class ParkingRepository(ABC):
    @abstractmethod
    async def create(self, data): ...
    @abstractmethod
    async def find_by_id(self, parking_id): ...
    @abstractmethod
    async def find_all(self): ...
    @abstractmethod
    async def update(self, parking_id, data): ...
    @abstractmethod
    async def delete(self, parking_id): ...
