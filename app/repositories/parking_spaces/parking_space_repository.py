from abc import ABC, abstractmethod

class ParkingSpaceRepository(ABC):
    @abstractmethod
    async def create(self, data): ...
    @abstractmethod
    async def find_by_id(self, space_id): ...
    @abstractmethod
    async def find_by_parking(self, parking_id, status=None, vehicle_type=None): ...
    @abstractmethod
    async def update(self, space_id, data): ...
    @abstractmethod
    async def delete(self, space_id): ...
