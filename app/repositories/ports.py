from typing import Protocol


class RepositoryConflictError(Exception):
    """A unique or relational constraint rejected a write."""


class UserRepositoryPort(Protocol):
    async def create(self, data: dict): ...
    async def find_by_id(self, user_id: str): ...
    async def find_by_email(self, email: str): ...
    async def find_all(self): ...
    async def update(self, user_id: str, data: dict): ...
    async def delete(self, user_id: str): ...


class VehicleRepositoryPort(Protocol):
    async def create(self, data: dict): ...
    async def find_by_id(self, vehicle_id: str): ...
    async def find_by_plate(self, plate: str): ...
    async def find_by_user(self, user_id: str): ...
    async def find_all(self): ...
    async def update(self, vehicle_id: str, data: dict): ...
    async def delete(self, vehicle_id: str): ...
    async def count_by_user(self, user_id: str) -> int: ...
